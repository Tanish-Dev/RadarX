export interface GeoCity {
  name: string;
  lat: number;
  lon: number;
}

const INDEX = new Map<string, GeoCity>();
for (const [name, lat, lon, ...aliases] of CITIES) {
  const c = { name, lat, lon };
  for (const k of [name, ...aliases]) INDEX.set(k.toLowerCase(), c);
}

/** All cities in a location string ("Bengaluru / Remote; Pune, India") — up to 3. */
export function geocode(location: string): GeoCity[] {
  const out: GeoCity[] = [];
  for (const part of location.split(/\s*(?:[\/;|]|\bor\b)\s*/i)) {
    const p = part.toLowerCase().trim();
    if (!p) continue;
    // try "city, region, country" → city; then the whole part
    const candidates = [p.split(",")[0].trim(), p, p.replace(/^(remote|hybrid)\s*(in|-|–)?\s*/, "")];
    let hit: GeoCity | undefined;
    for (const k of candidates) if ((hit = INDEX.get(k))) break;
    if (!hit) {
      // "Washington, DC" etc. — first two comma parts
      const two = p.split(",").slice(0, 2).join(",").trim();
      hit = INDEX.get(two);
    }
    if (hit && !out.includes(hit)) out.push(hit);
    if (out.length >= 3) break;
  }
  return out;
}
