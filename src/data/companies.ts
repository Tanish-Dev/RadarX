/**
 * Company registry. Each entry is either an explicit ATS config (verified with
 * a probe) or `auto` with candidate slugs — the worker then discovers the ATS
 * (Greenhouse → Lever → Ashby → SmartRecruiters) and caches it in `sources`.
 *
 * Companies with no public ATS API (Google, Meta, Apple, Jane Street, …) are
 * still listed so they show up on Source Health; their roles arrive via the
 * SimplifyJobs lists.
 */
import type { SourceConfig } from "../sources/types";

export type CompanyGroup =
  | "Big Tech"
  | "AI Labs"
  | "Fintech & Banks"
  | "Quant/HFT"
  | "Indian Startups"
  | "SaaS & Enterprise"
  | "Semiconductors & Hardware"
  | "Consulting & IT Services";

export type CompanySource = SourceConfig | { ats: "auto"; slugs: string[] } | { ats: "none"; note: string };

export interface Company {
  name: string;
  group: CompanyGroup;
  domain: string;
  source: CompanySource;
}

const auto = (name: string, group: CompanyGroup, domain: string, ...slugs: string[]): Company => ({
  name, group, domain, source: { ats: "auto", slugs },
});
const gh = (name: string, group: CompanyGroup, domain: string, slug: string): Company => ({
  name, group, domain, source: { ats: "greenhouse", slug },
});
const lv = (name: string, group: CompanyGroup, domain: string, slug: string): Company => ({
  name, group, domain, source: { ats: "lever", slug },
});
const ab = (name: string, group: CompanyGroup, domain: string, slug: string): Company => ({
  name, group, domain, source: { ats: "ashby", slug },
});
const sr = (name: string, group: CompanyGroup, domain: string, slug: string): Company => ({
  name, group, domain, source: { ats: "smartrecruiters", slug },
});
/** wd("Nvidia", …, "nvidia.wd5", "NVIDIAExternalCareerSite") — tenant is the first host label */
const wd = (name: string, group: CompanyGroup, domain: string, hostPrefix: string, site: string): Company => ({
  name, group, domain,
  source: { ats: "workday", host: `${hostPrefix}.myworkdayjobs.com`, tenant: hostPrefix.split(".")[0], site },
});
const ef = (name: string, group: CompanyGroup, domain: string, host: string, efDomain: string): Company => ({
  name, group, domain, source: { ats: "eightfold", host, domain: efDomain },
});
const none = (name: string, group: CompanyGroup, domain: string, note = "No public ATS API — covered by SimplifyJobs lists"): Company => ({
  name, group, domain, source: { ats: "none", note },
});

